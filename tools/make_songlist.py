#!/usr/bin/env python3
"""Regenerate the bundled song list from 3icecream.com's DDR song data.

    python3 tools/make_songlist.py

Writes core/src/main/resources/com/tehoubi/ddrtracker/core/songs/songs.tsv:
every DDR song 3icecream tracks (current and removed), with its title as the
game prints it, romanized and alternate names for typing it in, and the level
of each chart. Titles from the previous list that 3icecream doesn't have are
kept at the end, without levels. Standard library only.
"""
import json
import re
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "core/src/main/resources/com/tehoubi/ddrtracker/core/songs/songs.tsv"
SOURCE = "https://3icecream.com/js/songdata.js"

# Older songs the app has always recognised that the source no longer lists.
EXTRA = [
    "Butterfly", "Lachryma《Re:Queen'M》", "LET'S GET DOWN", "LOVE SHINE",
    "ONE MORE LOVELY", "SANA MOLLETE NE ENTE", "Sky High",
]


def key(title):
    """Same idea as SongKey: case, spacing and punctuation don't count."""
    return re.sub(r"[^0-9a-z]+", "", unicodedata.normalize("NFKC", title).lower()) or title


def clean(text):
    return " ".join(text.replace("\t", " ").split())


def main():
    with urllib.request.urlopen(SOURCE, timeout=60) as r:
        js = r.read().decode("utf-8")
    songs, _ = json.JSONDecoder().raw_decode(js[js.index("=") + 1:])

    rows, seen = [], set()
    for s in sorted(songs, key=lambda s: unicodedata.normalize("NFKC", s["song_name"]).lower()):
        title = clean(s["song_name"])
        if key(title) in seen:
            continue
        seen.add(key(title))
        aliases = []
        for field in ("romanized_name", "alternate_name", "searchable_name"):
            for alias in s.get(field, "").split("/"):
                alias = clean(alias)
                if alias and alias != title and alias not in aliases:
                    aliases.append(alias)
        levels = ",".join(str(n) for n in s["ratings"])
        rows.append(f"{title}\t{'|'.join(aliases)}\t{levels}")
    for title in EXTRA:
        if key(title) not in seen:
            rows.append(f"{title}\t\t")

    header = [
        "# Songs the scanner recognises, one per line, tab-separated:",
        "#   title as the game shows it",
        "#   other names for searching (romanized, alternate), separated by |",
        "#   chart levels: SP Beginner, Basic, Difficult, Expert, Challenge,",
        "#   then DP Basic, Difficult, Expert, Challenge (0 = no such chart)",
        f"# Generated by tools/make_songlist.py from {SOURCE}.",
        "# Titles the player saves that are not listed here are added on the device.",
    ]
    OUT.write_text("\n".join(header + rows) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} songs")


if __name__ == "__main__":
    main()
